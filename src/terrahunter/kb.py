"""The knowledge base: what each resource type is, how it connects, when it's exposed, and IAM data.

terrahunter ships a bundle built from the terrahunter knowledge base (`data/terrahunter-kb.json.gz`, generated by its
`scripts/build_bundle.py`). It holds the curated catalogue entries per cloud, the attack technique rules, AWS actions
with their access levels, every AWS managed policy's document, and the Azure and Google Cloud roles' permissions.
`--kb PATH` (or TERRAHUNTER_KB) reads another bundle instead: a bundle file, or a knowledge base checkout whose
`dist/` holds one.
"""

from __future__ import annotations

import fnmatch
import gzip
import json
import os
from functools import cache
from pathlib import Path

FORMAT = 1  # the bundle format this version reads
BUNDLE = "terrahunter-kb.json.gz"
PACKAGED = Path(__file__).with_name("data") / BUNDLE
MAX_BYTES = 64 * 1024 * 1024  # decompressed; the bundle is about 10 MB

_source: Path | None = None


class KBError(Exception):
    pass


def use(path: Path | None) -> None:
    """Read the knowledge base from this bundle or checkout from now on (None: the default)."""
    global _source
    _source = path
    _load.cache_clear()
    _actions.cache_clear()
    _gcp_permissions.cache_clear()


def location() -> Path:
    p = _source or (Path(os.environ["TERRAHUNTER_KB"]) if os.environ.get("TERRAHUNTER_KB") else None) or PACKAGED
    if p.is_dir():
        p = p / "dist" / BUNDLE
    return p


@cache
def _load() -> dict:
    p = location()
    try:
        with gzip.open(p, "rb") as f:
            raw = f.read(MAX_BYTES + 1)
    except (OSError, EOFError) as e:
        hint = " (build it with python scripts/build_bundle.py in the knowledge base)" if p.name == BUNDLE else ""
        raise KBError(f"can't read the knowledge base at {p}: {e}{hint}") from e
    if len(raw) > MAX_BYTES:
        raise KBError(f"the knowledge base at {p} is too large")
    try:
        data = json.loads(raw)
    except (ValueError, RecursionError) as e:
        raise KBError(f"the knowledge base at {p} isn't valid JSON: {e}") from e
    if not isinstance(data, dict) or data.get("format") != FORMAT:
        got = data.get("format") if isinstance(data, dict) else None
        raise KBError(f"the knowledge base at {p} is format {got}; this terrahunter reads format {FORMAT}")
    return data


def version() -> str:
    """The knowledge base commit the bundle was built from."""
    return str(_load().get("commit", ""))


def _cloud(rtype: str) -> str:
    return next((c for c, p in (("aws", "aws_"), ("azure", "azurerm_"), ("gcp", "google_")) if rtype.startswith(p)), "")


def canonical(rtype: str) -> str:
    """The type an alias stands for (aws_alb → aws_lb); the type itself otherwise."""
    return _load()["aliases"].get(rtype, rtype)


def entry(rtype: str) -> dict | None:
    """The curated catalogue entry for a resource type, or None when the knowledge base hasn't curated it."""
    t = canonical(rtype)
    return _load()["catalog"].get(_cloud(t), {}).get(t)


def curated(rtype: str) -> bool:
    return entry(rtype) is not None


def entries(cloud: str) -> dict[str, dict]:
    return _load()["catalog"].get(cloud, {})


def techniques(cloud: str) -> list[dict]:
    return _load()["techniques"].get(cloud, [])


# --- IAM ---------------------------------------------------------------------------------------------------------
def managed_policy(name: str) -> dict | None:
    """An AWS managed policy's default-version document, by name (AdministratorAccess)."""
    return _load()["iam"]["aws"].get("managed_policies", {}).get(name)


@cache
def _actions() -> dict[str, dict[str, tuple[str, str]]]:
    """service (lower case) → action (lower case) → (action as AWS writes it, access level)."""
    out: dict[str, dict[str, tuple[str, str]]] = {}
    for svc, acts in _load()["iam"]["aws"].get("actions", {}).items():
        out[svc.lower()] = {a.lower(): (a, level) for a, level in acts.items()}
    return out


def aws_actions(pattern: str) -> list[tuple[str, str]]:
    """The actions an IAM action pattern matches ('s3:Get*', 's3:*', '*'), as ('s3:GetObject', 'Read') pairs.
    Names compare case-insensitively, as IAM does. An action the data doesn't know gives nothing."""
    p = pattern.strip().lower()
    acts = _actions()
    if p == "*":
        return [(f"{s}:{a}", level) for s, m in acts.items() for a, level in m.values()]
    svc, sep, act = p.partition(":")
    if not sep:
        return []
    services = [s for s in acts if fnmatch.fnmatchcase(s, svc)] if any(c in svc for c in "*?") else [svc]
    out = []
    for s in services:
        m = acts.get(s, {})
        if not any(c in act for c in "*?"):
            if act in m:
                out.append((f"{s}:{m[act][0]}", m[act][1]))
            continue
        out += [(f"{s}:{a}", level) for k, (a, level) in m.items() if fnmatch.fnmatchcase(k, act)]
    return out


def azure_role(name: str) -> list[dict] | None:
    """An Azure built-in role's permissions ([{actions, not_actions, data_actions, not_data_actions}]), by name."""
    return _load()["iam"]["azure"].get("roles", {}).get(name)


@cache
def _gcp_permissions() -> list[str]:
    return _load()["iam"]["gcp"].get("permissions", [])


def gcp_role(name: str) -> list[str] | None:
    """A Google Cloud predefined role's permissions, by name (roles/storage.objectViewer)."""
    idx = _load()["iam"]["gcp"].get("roles", {}).get(name)
    if idx is None:
        return None
    perms = _gcp_permissions()
    return [perms[i] for i in idx]
